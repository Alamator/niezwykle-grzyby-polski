// Builds data/map-points.js: every place of the atlas for the map of the whole cabinet (/mapa), one entry
// per Wikidata item with the cards that describe it. That map shows all places before any collection
// loads, so these are copies of data/places and of the card names; scripts/validate-collections.mjs fails
// when a copy no longer matches. Run after changing a map point or a card name: npm run build:map-points
import fs from "node:fs";
import { pathToFileURL } from "node:url";
import { loadAtlas } from "./build-start-page.mjs";

export function buildMapPoints(win) {
  const app = win.ATLAS_APP_DATA;
  const english = win.ATLAS_I18N.collections.en;
  const places = new Map();
  for (const collection of app.collections) {
    for (const item of collection.items) {
      const point = collection.places?.[item.id];
      if (!point) continue;
      if (!places.has(point.wikidata)) places.set(point.wikidata, { q: point.wikidata, lat: point.lat, lng: point.lng, cards: [] });
      const place = places.get(point.wikidata);
      if (place.lat !== point.lat || place.lng !== point.lng) {
        throw new Error(`${point.wikidata}: ${collection.id}/${item.id} gives other coordinates than the cards before it`);
      }
      place.cards.push({ collection: collection.id, id: item.id, name: { pl: item.name_pl, en: english[collection.id].items[item.id].name } });
    }
  }
  return { places: [...places.values()] };
}

// One place per line, so a changed point shows as one changed line.
export function mapPointsSource(data) {
  return `// Generated by scripts/build-map-points.mjs from data/places and the cards; do not edit by hand.
// Every place of the atlas, one per Wikidata item, with the cards that describe it, for the map at /mapa.
window.ATLAS_MAP_POINTS = {
  "places": [
${data.places.map((place) => `    ${JSON.stringify(place)}`).join(",\n")}
  ]
};
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const data = buildMapPoints(loadAtlas());
  fs.writeFileSync("data/map-points.js", mapPointsSource(data));
  const cards = data.places.reduce((sum, place) => sum + place.cards.length, 0);
  console.log(`data/map-points.js: ${data.places.length} places, ${cards} cards`);
}

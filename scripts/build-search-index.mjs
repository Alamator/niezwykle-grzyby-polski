// Builds data/search-index.js: what "Szukaj w całym atlasie" on the start page looks through, one row per card
// of every collection. The page loads it only when somebody starts typing, so the start page stays light.
// scripts/validate-collections.mjs fails when the index no longer matches the cards.
// Run after adding a card or changing a name: npm run build:search-index
import fs from "node:fs";
import { pathToFileURL } from "node:url";
import { loadAtlas } from "./build-start-page.mjs";

// A row: [collection, card id, Polish name, English name, Latin name or the line under a place's name,
// that line in English when it differs, then the card's former names in the atlas, if any].
export function buildSearchIndex(win) {
  const english = win.ATLAS_I18N.collections.en;
  const cards = win.ATLAS_APP_DATA.collections.flatMap((collection) => collection.items.map((item) => {
    const en = english[collection.id].items[item.id];
    const latinEn = en.latin && en.latin !== item.name_lat ? en.latin : "";
    return [collection.id, item.id, item.name_pl, en.name, item.name_lat || "", latinEn, ...(item.synonyms || [])];
  }));
  return { v: 1, cards };
}

export function searchIndexSource(data) {
  return `// Generated by scripts/build-search-index.mjs from the cards; do not edit by hand.
// "Szukaj w całym atlasie" on the start page loads it on first use. A row: collection, card id, Polish name,
// English name, Latin name or the line under a place's name, that line in English, former names in the atlas.
window.ATLAS_SEARCH = {
  "v": ${data.v},
  "cards": [
${data.cards.map((row) => `    ${JSON.stringify(row)}`).join(",\n")}
  ]
};
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const data = buildSearchIndex(loadAtlas());
  fs.writeFileSync("data/search-index.js", searchIndexSource(data));
  console.log(`data/search-index.js: ${data.cards.length} cards`);
}
